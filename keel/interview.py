"""The kickoff interview: the questions that give Keel its first picture of you.

The shape follows Dan McAdams' Life Story Interview (chapters, key scenes,
values, the future), in our own words. Stanford's 1,052-person study found a
two-hour interview like this was enough for a model to answer survey
questions about 83% as consistently as people matched their own answers two
weeks later. Answers are saved as ordinary entries, so "forget that" and
`keel forget` work on them too.
"""

QUESTIONS = [
    "If your life were a book, what would the chapters be? Just a title and roughly when each one starts.",
    "Tell me about a high point, a moment that felt like the best of you. What happened, who was there, and what were you thinking?",
    "Now a low point. Take your time, or say skip.",
    "A turning point: a moment after which things went differently.",
    "What's your earliest memory that still feels vivid?",
    "Who has shaped you most, for better or worse?",
    "What are you working toward right now, and why does it matter to you?",
    "What do you believe that most people around you don't?",
    "When you're at your worst, what does it look like? How would someone close to you spot it?",
    "And at your best, what's different?",
    "What should I never let you get away with?",
    "When you're low, what actually helps, and what makes it worse?",
    "Where do you want to be in five years? What would make you proud?",
    "What's the thread that runs through your whole story?",
]
